@Injectable({ providedIn: 'root' })
export class I18nService {
  readonly currentLang = signal<SupportedLang>('es');

  constructor() {
    this.initLang();
  }

  private initLang() {
    if (typeof window === 'undefined') return;
    const saved = localStorage.getItem(LANG_KEY) as SupportedLang;
    if (saved === 'es' || saved === 'en') {
      this.currentLang.set(saved);
    } else {
      const browserLang = navigator.language?.toLowerCase() || '';
      this.currentLang.set(browserLang.startsWith('es') ? 'es' : 'en');
    }
  }

  setLang(lang: SupportedLang) {
    this.currentLang.set(lang);
    if (typeof window !== 'undefined') {
      localStorage.setItem(LANG_KEY, lang);
    }
  }

  t(key: string, fallbackOrParams?: string | Record<string, any>, params?: Record<string, any>): string {
    const lang = this.currentLang();
    const dict = TRANSLATIONS[lang] || TRANSLATIONS.es;

    let res = dict[key];

    // Alias fallbacks for keys that might have .btn suffix or alternative naming
    if (!res) {
      if (key === 'community.follow') res = dict['community.follow.btn'];
      else if (key === 'community.following') res = dict['community.following.btn'];
      else if (key === 'community.follow.btn') res = dict['community.follow'];
      else if (key === 'community.following.btn') res = dict['community.following'];
    }

    let actualParams: Record<string, any> | undefined;
    let fallbackText: string | undefined;

    if (typeof fallbackOrParams === 'object' && fallbackOrParams !== null) {
      actualParams = fallbackOrParams;
    } else {
      fallbackText = fallbackOrParams;
      actualParams = params;
    }

    if (!res) {
      if (lang === 'en' && TRANSLATIONS.en[key]) {
        res = TRANSLATIONS.en[key];
      } else if (lang === 'es' && TRANSLATIONS.es[key]) {
        res = TRANSLATIONS.es[key];
      } else {
        res = fallbackText || key;
      }
    }

    if (actualParams && typeof res === 'string') {
      for (const [pKey, pVal] of Object.entries(actualParams)) {
        res = res.replace(new RegExp(`\\{${pKey}\\}`, 'g'), String(pVal));
      }
    }

    return res;
  }
}

